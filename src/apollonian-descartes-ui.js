// Browser-only adapter for the canonical Apollonian / Descartes packing.
//
// The renderer deliberately reuses retired numeric id 8 (`penrose`) so every
// already-shipped shape id remains stable. index.html still hand-writes its
// selector, wall notes and HUD name array, so this adapter gives that dormant id
// its new public presentation until those three UI lists are generated from one
// registry. It does nothing outside the explorer page.

const INTERNAL_KEY = 'penrose';
const PUBLIC_HUD = 'apollonian-descartes';
const TITLE = 'Canonical Apollonian sphere packing (Descartes)';
const NOTE = 'A true three-dimensional Apollonian packing: four spheres tangent inside an enclosing sphere, with their curvatures constrained by the Soddy–Gossett form of Descartes’ theorem. Each recursive sphere is generated by a dual inversion that replaces one member of a tangent Descartes configuration.';

export function installApollonianDescartesUI() {
  if (typeof document === 'undefined') return;

  const install = () => {
    const select = document.getElementById('sel-fractal');
    if (!select) return;

    if (!select.querySelector(`option[value="${INTERNAL_KEY}"]`)) {
      const option = document.createElement('option');
      option.value = INTERNAL_KEY;
      option.textContent = TITLE;
      option.dataset.canonicalApollonian = '1';
      const anchor = select.querySelector('option[value="apollonian"]');
      if (anchor) anchor.after(option);
      else select.appendChild(option);
    }

    // index.html's private NOTES table predates this runtime extension. Its
    // change handler hides unknown notes, so queue our note until that handler
    // has completed rather than racing it during the same event dispatch.
    const showCanonicalNote = () => {
      if (select.value !== INTERNAL_KEY) return;
      queueMicrotask(() => {
        if (select.value !== INTERNAL_KEY) return;
        const note = document.getElementById('model-note');
        if (!note) return;
        note.style.display = '';
        const title = note.querySelector('b');
        const body = note.querySelector('span');
        if (title) title.textContent = 'Canonical Apollonian packing';
        if (body) body.textContent = NOTE;
        note.classList.remove('dismissed');
      });
    };
    select.addEventListener('change', showCanonicalNote);

    // The HUD also carries the old internal name at id 8. Keep the numeric id
    // private by rewriting only that prefix; all quality/fps/zoom text remains
    // owned by the existing HUD loop.
    const hud = document.getElementById('hud');
    if (hud && typeof MutationObserver !== 'undefined') {
      const syncHudName = () => {
        const text = hud.textContent || '';
        if (select.value === INTERNAL_KEY && text.startsWith(`${INTERNAL_KEY} ·`)) {
          hud.textContent = PUBLIC_HUD + text.slice(INTERNAL_KEY.length);
        }
      };
      new MutationObserver(syncHudName).observe(hud, {
        childList: true,
        subtree: true,
        characterData: true,
      });
      syncHudName();
    }
  };

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', install, { once: true });
  } else {
    install();
  }
}
